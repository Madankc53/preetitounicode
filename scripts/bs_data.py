def bs_to_ad(y, m, d):
    x = BASE_AD
    for yy in range(2000, y):
        x += datetime.timedelta(sum(CANONICAL[yy]))
    for mm in range(m - 1):
        x += datetime.timedelta(CANONICAL[y][mm])
    return x + datetime.timedelta(d - 1)


def js_rows(indent="  ", per_line=1):
    """JS object body used by every embedded copy."""
    items = [f"{y}:[{','.join(map(str, CANONICAL[y]))}]" for y in sorted(CANONICAL)]
    lines = [indent + ",".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return ",\n".join(lines)
