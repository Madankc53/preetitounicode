#!/usr/bin/env python3
"""Extract the Preeti->Unicode engine from preeti-to-unicode-converter/index.html into assets/preeti-fwd.js
so other pages (e.g. Preeti to Kalimati) share the exact same, tested engine."""
import re
idx=open('preeti-to-unicode-converter/index.html',encoding='utf-8').read()
a=idx.index('const MAPS = {'); b=idx.index('// ═══',idx.index('// Build reverse maps'))
c=idx.index('function applyRules(t,rules){'); d=idx.index('function revConvert(t,font){')
e=idx.index('\n}\n',d)+3
js='/* Generated by scripts/build_preeti_fwd.py from preeti-to-unicode-converter/index.html. Do not edit. */\n(function(root){\n'+idx[a:b]+idx[c:e]+'root.PreetiFwd={convert:function(t,f){return fwdConvert(t,f||"preeti")},rev:function(t,f){return revConvert(t,f||"preeti")}};\n})(typeof self!=="undefined"?self:this);\n'
open('assets/preeti-fwd.js','w',encoding='utf-8').write(js)
print(len(js))
